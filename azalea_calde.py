df['hs'] = df['hs'].map(mapping_hs)
df['irony'] = df['irony'].map(mapping_irony)
df['stance'] = df['stance'].map(mapping_stance)

# Controlliamo se la colonna 'profile' ha i valori attesi
print(df['profile'].unique())  # Verifica se esistono 'high' e 'low'

# Creazione di un pivot più semplice per evitare MultiIndex errati
pivot_social = df[df['profile'] == 'high'].set_index('tweet_id')[['stance']]
pivot_no_social = df[df['profile'] == 'low'].set_index('tweet_id')[['stance']]

# Unione dei due dataframe per il confronto
pivot_merged = pivot_social.join(pivot_no_social, lsuffix='_high', rsuffix='_low')

# Funzione per calcolare la percentuale di accordo
def agreement_percentage(pivot_data, column, exclude_value=None):
    if exclude_value is not None:
        valid_data = pivot_data.loc[~((pivot_data[column + '_high'] == exclude_value) |
                                      (pivot_data[column + '_low'] == exclude_value))]
    else:
        valid_data = pivot_data

    agreement = (valid_data[column + '_high'] == valid_data[column + '_low']).sum()
    total = len(valid_data)
    return (agreement / total) * 100 if total > 0 else 0  # Evita divisioni per zero

# Calcolo delle percentuali di accordo con e senza None per stance nei due gruppi
agreement_stance_with_none = agreement_percentage(pivot_merged, 'stance')  # Include 'none'
agreement_stance_without_none = agreement_percentage(pivot_merged, 'stance', exclude_value=1)  # Esclude 'none'

# Creazione del grafico a doppia barra per confrontare i due calcoli
labels = ['Stance - Con None', 'Stance - Senza None']
values = [agreement_stance_with_none, agreement_stance_without_none]

x = np.arange(len(labels))  # Posizione delle etichette
width = 0.35  # Larghezza delle barre

fig, ax = plt.subplots(figsize=(8, 6))
