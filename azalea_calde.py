import pandas as pd
import numpy as np
from sklearn.metrics import cohen_kappa_score
from statsmodels.stats.inter_rater import fleiss_kappa

# 1. Caricamento del dataset
file_path = "/content/sample_data/Azalea-annotations_2025-02-11 (1).csv"
df = pd.read_csv(file_path)


# 2. Mappatura delle categorie in numeri
mapping_hs = {'yes': 1, 'no': 0}
mapping_irony = {'yes': 1, 'no': 0}
mapping_stance = {'favor': 2, 'none': 1, 'against': 0}  # Valori non negativi per il Fleiss' Kappa

df['hs'] = df['hs'].map(mapping_hs)
df['irony'] = df['irony'].map(mapping_irony)
df['stance'] = df['stance'].map(mapping_stance)

# 3. Divisione del dataset in base al profilo degli annotatori
df_high = df[df['profile'] == 'high']
df_low = df[df['profile'] == 'low']

# 4. Funzione per creare la matrice di conteggio per il Fleiss' Kappa
def create_fleiss_matrix(data, column, n_categories=3):
    """
    Raggruppa i dati per tweet e conta quante annotazioni ricadono in ciascuna categoria.
    n_categories: numero totale di categorie possibili.
    """
    # Raggruppa per 'tweet_id' e conta le occorrenze per ciascuna categoria
    grouped = data.groupby('tweet_id')[column].apply(
        lambda x: np.bincount(x.dropna().astype(int), minlength=n_categories)
    )
    return np.vstack(grouped.values)

# 5. Creazione delle matrici per il calcolo del Fleiss' Kappa
# (Notare che per 'hs' e 'irony' ci sono solo 2 categorie, ma usiamo minlength=3 per uniformità;
#  la terza colonna rimarrà sempre a zero.)
matrix_hs = create_fleiss_matrix(df, 'hs', n_categories=3)
matrix_stance = create_fleiss_matrix(df, 'stance', n_categories=3)
matrix_irony = create_fleiss_matrix(df, 'irony', n_categories=3)

# 6. Calcolo del Fleiss' Kappa per tutti gli annotatori
fleiss_hs = fleiss_kappa(matrix_hs)
fleiss_stance = fleiss_kappa(matrix_stance)
fleiss_irony = fleiss_kappa(matrix_irony)

# 7. Calcolo del Cohen's Kappa confrontando le annotazioni dei profili "high" e "low"
# Si assume che per ogni tweet esista una sola annotazione per ciascun profilo.
pivot = df.pivot_table(index='tweet_id', columns='profile', aggfunc='first')

kappa_hs = cohen_kappa_score(pivot[('hs', 'high')], pivot[('hs', 'low')])
kappa_stance = cohen_kappa_score(pivot[('stance', 'high')], pivot[('stance', 'low')])
kappa_irony = cohen_kappa_score(pivot[('irony', 'high')], pivot[('irony', 'low')])

# 8. Calcolo del Fleiss' Kappa per i sottogruppi (high e low)
fleiss_hs_high = fleiss_kappa(create_fleiss_matrix(df_high, 'hs'))
fleiss_stance_high = fleiss_kappa(create_fleiss_matrix(df_high, 'stance'))
fleiss_irony_high = fleiss_kappa(create_fleiss_matrix(df_high, 'irony'))

fleiss_hs_low = fleiss_kappa(create_fleiss_matrix(df_low, 'hs'))
fleiss_stance_low = fleiss_kappa(create_fleiss_matrix(df_low, 'stance'))
fleiss_irony_low = fleiss_kappa(create_fleiss_matrix(df_low, 'irony'))

# 9. Visualizzazione dei risultati
results = {
    "Cohen's Kappa - Hate Speech": kappa_hs,
    "Cohen's Kappa - Stance": kappa_stance,
    "Cohen's Kappa - Irony": kappa_irony,
    "Fleiss' Kappa - Hate Speech": fleiss_hs,
    "Fleiss' Kappa - Stance": fleiss_stance,
    "Fleiss' Kappa - Irony": fleiss_irony,
    "Fleiss' Kappa High Profile - Hate Speech": fleiss_hs_high,
    "Fleiss' Kappa High Profile - Stance": fleiss_stance_high,
    "Fleiss' Kappa High Profile - Irony": fleiss_irony_high,
    "Fleiss' Kappa Low Profile - Hate Speech": fleiss_hs_low,
    "Fleiss' Kappa Low Profile - Stance": fleiss_stance_low,
    "Fleiss' Kappa Low Profile - Irony": fleiss_irony_low,
}

for key, value in results.items():
    print(f"{key}: {value:.4f}")

